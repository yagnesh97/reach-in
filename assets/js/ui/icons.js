const Icons = Object.freeze(
  Object.fromEntries(Object.keys(ICON_PATHS).map((key) => [key, key]))
);

function renderIcon(name, options = {}) {
  const { className = "", size } = options;
  const paths = ICON_PATHS[name];
  if (!paths) return document.createDocumentFragment();

  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "2");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  if (className) svg.setAttribute("class", className);
  if (size) {
    svg.style.width = `${size}px`;
    svg.style.height = `${size}px`;
  }
  svg.innerHTML = paths;
  return svg;
}

function createIconButton(name, options = {}) {
  const {
    label,
    className = "btn btn-icon",
    id,
    disabled = false,
    type = "button",
    showLabel = false,
  } = options;

  const button = document.createElement("button");
  button.type = type;
  button.className = className;
  if (id) button.id = id;
  if (label) {
    button.setAttribute("aria-label", label);
    button.setAttribute("title", label);
  }
  button.disabled = disabled;
  button.appendChild(renderIcon(name));

  if (showLabel && label) {
    const span = document.createElement("span");
    span.textContent = label;
    button.appendChild(span);
  }

  return button;
}

function setButtonIcon(button, name) {
  const existingSvg = button.querySelector("svg");
  const newSvg = renderIcon(name);
  if (existingSvg) {
    existingSvg.replaceWith(newSvg);
  } else {
    button.prepend(newSvg);
  }
}

function flashButtonSuccess(button, duration = 1500) {
  button.classList.add("is-success");
  setTimeout(() => button.classList.remove("is-success"), duration);
}
